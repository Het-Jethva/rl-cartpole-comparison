"""Table generation, plus the numbers the paper's prose quotes.

Three LaTeX tables and one file of macros are written here. The macros matter:
every number that appears in the running text is defined as a command generated
from the results, so the prose cannot drift out of step with the data.

`count_code_lines` supplies the implementation-cost column. It counts statements,
not bytes: blank lines, comments and docstrings are excluded, so a well-commented
implementation is not punished.
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import Any

import numpy as np

from ..experiments.results import load_group
from .stats import group_by_arm, iqm, summarize_arm

METHOD_LABELS = {
    "tabular": "Tabular Q-learning",
    "dqn": "DQN",
    "reinforce": "REINFORCE + baseline",
}
METHOD_SOURCES = {
    "tabular": "agents/tabular.py",
    "dqn": "agents/dqn.py",
    "reinforce": "agents/reinforce.py",
}


def count_code_lines(path: Path) -> int:
    """Count executable source lines: no blanks, no comments, no docstrings."""
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source)
    docstring_lines: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if ast.get_docstring(node, clean=False) is not None:
                first = node.body[0]
                docstring_lines.update(range(first.lineno, (first.end_lineno or first.lineno) + 1))
    total = 0
    for number, line in enumerate(source.splitlines(), start=1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or number in docstring_lines:
            continue
        total += 1
    return total


def _escape(text: str) -> str:
    return text.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def _steps(value: float | None) -> str:
    return "---" if value is None else f"{value / 1000:.0f}k"


def table_tradeoff(
    study: dict[str, Any], results_root: Path, out: Path, package_root: Path
) -> Path:
    """Table I: the paper's central contribution."""
    runs = group_by_arm(load_group("main", results_root))
    rows = []
    for method in study["methods"]:
        if method not in runs:
            continue
        summary = summarize_arm(runs[method])
        lines = count_code_lines(package_root / METHOD_SOURCES[method])
        hyperparameters = int(summary.diagnostics.get("hyperparameter_count", 0))
        rows.append(
            f"{METHOD_LABELS[method]} & "
            f"{_steps(summary.steps_to_solve_median)} & "
            f"{summary.final_iqm:.0f} "
            f"[{summary.final_ci[0]:.0f}, {summary.final_ci[1]:.0f}] & "
            f"{summary.wall_clock_mean:.0f} & "
            f"{summary.updates_mean / 1000:.0f}k & "
            f"{summary.failure_rate * 100:.0f}\\% & "
            f"{lines} / {hyperparameters} \\\\"
        )

    body = "\n".join(rows)
    # Seven columns cannot fit one IEEE column, so this spans the page.
    latex = rf"""% Generated by rlcompare. Do not edit by hand.
\begin{{table*}}[t]
\centering
\caption{{Trade-off summary over {len(next(iter(runs.values())))} seeds per method,
under an identical budget of {study['run']['total_steps'] // 1000}k environment steps.
Steps-to-solve is the median over the seeds that reached the threshold.
Final return is the interquartile mean with a 95\% bootstrap interval.
Implementation cost counts executable source lines in the agent module and the
number of tunable hyperparameters; the shared training loop is excluded because
it is identical for all three methods.}}
\label{{tab:tradeoff}}
\begin{{tabular}}{{lcccccc}}
\toprule
Method & Steps to & Final return & Wall clock & Gradient & Failed & LoC / \\
 & solve & (IQM [95\% CI]) & (s) & updates & seeds & hyperparams \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table*}}
"""
    path = out / "tradeoff.tex"
    path.write_text(latex, encoding="utf-8")
    return path


def table_hyperparameters(study: dict[str, Any], tuned: dict[str, Any], out: Path) -> Path:
    """Table II: the selected hyperparameters, for the appendix."""
    from ..config import build_params

    blocks = []
    for method in study["methods"]:
        params = build_params(method, tuned.get(method, {}))
        selected = set(tuned.get(method, {}))
        blocks.append(rf"\multicolumn{{3}}{{l}}{{\textit{{{METHOD_LABELS[method]}}}}} \\")
        for field_name, value in sorted(vars(params).items()):
            mark = r"$\star$" if field_name in selected else ""
            blocks.append(
                f"\\quad {_escape(field_name)} & {_escape(str(value))} & {mark} \\\\"
            )
        blocks.append(r"\addlinespace")

    body = "\n".join(blocks[:-1])
    latex = rf"""% Generated by rlcompare. Do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{Complete hyperparameter settings. Values marked $\star$ were selected by
the equal-budget random search ({study['tuning']['trials']} trials per method,
{len(study['seeds']['tuning'])} tuning seeds each); the rest are fixed defaults
shared by every arm.}}
\label{{tab:hyperparameters}}
\begin{{tabular}}{{llc}}
\toprule
Parameter & Value & Tuned \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    path = out / "hyperparameters.tex"
    path.write_text(latex, encoding="utf-8")
    return path


def table_ablations(study: dict[str, Any], results_root: Path, out: Path) -> Path:
    """Extended analysis: each component removal against its full method."""
    main = group_by_arm(load_group("main", results_root))
    ablation = group_by_arm(load_group("ablation", results_root))

    rows = []
    for name, spec in study["ablations"].items():
        method = spec["method"]
        if method not in main:
            continue
        full = summarize_arm(main[method])
        rows.append(
            f"{METHOD_LABELS[method]} & "
            f"{full.final_iqm:.0f} [{full.final_ci[0]:.0f}, {full.final_ci[1]:.0f}] & "
            f"{_steps(full.steps_to_solve_median)} & "
            f"{full.failure_rate * 100:.0f}\\% \\\\"
        )
        arm = f"{method}:{name}"
        if arm not in ablation:
            continue
        removed = summarize_arm(ablation[arm])
        rows.append(
            f"\\quad {_escape(spec.get('short_label', spec['label']))} & "
            f"{removed.final_iqm:.0f} [{removed.final_ci[0]:.0f}, {removed.final_ci[1]:.0f}] & "
            f"{_steps(removed.steps_to_solve_median)} & "
            f"{removed.failure_rate * 100:.0f}\\% \\\\"
        )
        rows.append(r"\addlinespace")

    body = "\n".join(rows[:-1]) if rows else "---"
    latex = rf"""% Generated by rlcompare. Do not edit by hand.
\begin{{table}}[t]
\centering
\caption{{Component ablations. Each removal is a one-flag change from the tuned
configuration, run on the same {len(study['seeds']['evaluation'])} evaluation seeds.}}
\label{{tab:ablations}}
\footnotesize
\setlength{{\tabcolsep}}{{3.5pt}}
\begin{{tabular}}{{lccc}}
\toprule
Arm & Final return & Steps to & Failed \\
 & (IQM [95\% CI]) & solve & seeds \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{table}}
"""
    path = out / "ablations.tex"
    path.write_text(latex, encoding="utf-8")
    return path


def macros(
    study: dict[str, Any], results_root: Path, out: Path, package_root: Path
) -> Path:
    """Every number the prose quotes, as LaTeX commands.

    Defining these from the results is what stops the text and the data drifting
    apart when the study is rerun.
    """
    main = group_by_arm(load_group("main", results_root))
    ablation = group_by_arm(load_group("ablation", results_root))
    lines = [r"% Generated by rlcompare. Do not edit by hand."]

    def define(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\{name}}}{{{value}}}")

    define("NumSeeds", str(len(study["seeds"]["evaluation"])))
    define("NumTuningSeeds", str(len(study["seeds"]["tuning"])))
    define("NumTrials", str(study["tuning"]["trials"]))
    define("StepBudget", f"{study['run']['total_steps'] // 1000}k")
    define("EvalEvery", f"{study['run']['eval_every'] // 1000}k")
    define("EvalEpisodes", str(study["run"]["eval_episodes"]))
    define("SolvedThreshold", str(int(study["run"]["solved_threshold"])))

    total_runs = 0
    for group in ("main", "sweep", "ablation", "tuning"):
        count = len(load_group(group, results_root))
        total_runs += count
        define(f"NumRuns{group.capitalize()}", str(count))
    define("NumRunsTotal", str(total_runs))

    for method in study["methods"]:
        if method not in main:
            continue
        summary = summarize_arm(main[method])
        prefix = {"tabular": "Tab", "dqn": "Dqn", "reinforce": "Rei"}[method]
        define(f"{prefix}Final", f"{summary.final_iqm:.0f}")
        define(f"{prefix}CiLow", f"{summary.final_ci[0]:.0f}")
        define(f"{prefix}CiHigh", f"{summary.final_ci[1]:.0f}")
        define(f"{prefix}Time", f"{summary.wall_clock_mean:.0f}")
        define(f"{prefix}Updates", f"{summary.updates_mean / 1000:.0f}k")
        define(f"{prefix}Failure", f"{summary.failure_rate * 100:.0f}")
        define(f"{prefix}Solve", _steps(summary.steps_to_solve_median))
        define(f"{prefix}Loc", str(count_code_lines(package_root / METHOD_SOURCES[method])))
        define(f"{prefix}Hyper", str(int(summary.diagnostics.get("hyperparameter_count", 0))))

    if "tabular" in main:
        summary = summarize_arm(main["tabular"])
        define("TabCoverage", f"{summary.diagnostics.get('state_coverage', 0) * 100:.0f}")
        define("TabCells", f"{int(summary.diagnostics.get('table_cells', 0)):,}".replace(",", r"\,"))
        define("TabEntries", f"{int(summary.diagnostics.get('table_entries', 0)):,}".replace(",", r"\,"))
    if "dqn" in main:
        summary = summarize_arm(main["dqn"])
        define("DqnParams", f"{int(summary.diagnostics.get('parameters', 0)):,}".replace(",", r"\,"))
    if "reinforce" in main:
        summary = summarize_arm(main["reinforce"])
        define("ReiParams", f"{int(summary.diagnostics.get('parameters', 0)):,}".replace(",", r"\,"))

    for name, spec in study["ablations"].items():
        arm = f"{spec['method']}:{name}"
        if arm not in ablation:
            continue
        summary = summarize_arm(ablation[arm])
        key = "NoBaseline" if "baseline" in name else "NoTarget"
        define(f"Abl{key}Final", f"{summary.final_iqm:.0f}")
        define(f"Abl{key}Failure", f"{summary.failure_rate * 100:.0f}")
        define(f"Abl{key}Solve", _steps(summary.steps_to_solve_median))

    # Sweep extremes, quoted in the Extended Analysis section.
    sweep = group_by_arm(load_group("sweep", results_root))
    for method, spec in study["sweeps"].items():
        prefix = {"tabular": "Tab", "dqn": "Dqn", "reinforce": "Rei"}[method]
        finals = {}
        for value in spec["values"]:
            label = "x".join(str(v) for v in value) if isinstance(value, list) else str(value)
            arm = f"{method}:{spec['parameter']}={label}"
            if arm in sweep:
                finals[label] = iqm([r.final_mean for r in sweep[arm]])
        if finals:
            best = max(finals, key=lambda k: finals[k])
            worst = min(finals, key=lambda k: finals[k])
            define(f"{prefix}SweepBest", _escape(best))
            define(f"{prefix}SweepBestValue", f"{finals[best]:.0f}")
            define(f"{prefix}SweepWorst", _escape(worst))
            define(f"{prefix}SweepWorstValue", f"{finals[worst]:.0f}")
            define(f"{prefix}SweepSpread", f"{max(finals.values()) - min(finals.values()):.0f}")

    path = out / "numbers.tex"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def build_all_tables(
    study: dict[str, Any],
    tuned: dict[str, Any],
    results_root: Path,
    out: Path,
    package_root: Path,
) -> list[Path]:
    """Write every table. `package_root` is the directory holding `agents/`,
    used only to count source lines for the implementation-cost column."""
    out.mkdir(parents=True, exist_ok=True)
    written = []
    builders = [
        lambda: table_tradeoff(study, results_root, out, package_root),
        lambda: table_hyperparameters(study, tuned, out),
        lambda: table_ablations(study, results_root, out),
        lambda: macros(study, results_root, out, package_root),
    ]
    for builder in builders:
        try:
            written.append(builder())
        except (ValueError, KeyError, IndexError, StopIteration) as error:
            print(f"  skipped a table: {error}")
    return written
